#!/usr/bin/env python3
"""Regenerate src/openehr-terms.js from the openEHR terminology XML.

Usage: python3 scripts/build-openehr-terms.py path/to/openehr_terminology.xml
Source: https://github.com/openEHR/specifications-TERM/blob/master/computable/XML/en/openehr_terminology.xml
"""
import json, sys, xml.etree.ElementTree as ET

root = ET.parse(sys.argv[1]).getroot()
terms = {}
for group in root.iter("group"):
    for c in group.iter("concept"):
        terms[c.get("id")] = {"rubric": c.get("rubric"), "group": group.get("openehr_id")}
out = ("// Generated by scripts/build-openehr-terms.py from openEHR terminology "
       f"{root.get('version')} ({root.get('date')}). Do not edit by hand.\n"
       "export const OPENEHR_TERMS = " + json.dumps(terms, sort_keys=True, ensure_ascii=False, separators=(",", ":")).replace("},", "},\n") + ";\n")
open("src/openehr-terms.js", "w").write(out)
print(f"{len(terms)} openEHR concepts written")
